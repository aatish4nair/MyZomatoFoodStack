/**
 * `npm run dish:categories`: checks the Dish Category mapping against YOUR order data.
 *
 * The terminal shows counts only. The full mapping (dish names, which contain personal order
 * information) is written ONLY to `private/dish-categories.md` (ignored by Git), including every
 * dish that fell into `Other` and the dishes decided by explicit overrides, for review.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  categorizeDish,
  DISH_CATEGORIES,
  DISH_CATEGORY_OVERRIDES,
  dishTypeOf,
  isCountedOrder,
} from '@food-stack/shared';
import { loadEnv, sheetsConfig } from '../config/env.js';
import { createSheetsReader } from '../integrations/google-sheets/sheets-reader.js';
import { DATA_ERROR_MESSAGES, DataUnavailableError } from '../lib/data-errors.js';
import { parseSheet } from '../modules/orders/parse-sheet.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');

async function main(): Promise<void> {
  const config = sheetsConfig(loadEnv());
  if (!config) {
    console.log(
      'Not configured: set GOOGLE_SHEET_ID and a service-account credential in backend/.env.',
    );
    process.exitCode = 1;
    return;
  }
  const { orders } = parseSheet(await createSheetsReader(config).readValues());
  const dishes = new Map<
    string,
    { name: string; originals: Set<string>; categories: Set<string> }
  >();
  for (const item of orders.filter(isCountedOrder).flatMap((o) => o.items)) {
    const { key, name } = dishTypeOf(item.name);
    const entry = dishes.get(key) ?? { name, originals: new Set(), categories: new Set() };
    entry.originals.add(item.name);
    entry.categories.add(categorizeDish(item.name));
    dishes.set(key, entry);
  }

  const byCategory = new Map<string, string[]>(DISH_CATEGORIES.map((c) => [c, []]));
  const conflicts: string[] = [];
  for (const dish of dishes.values()) {
    if (dish.categories.size > 1) conflicts.push(dish.name);
    for (const category of dish.categories) byCategory.get(category)?.push(dish.name);
  }
  const overridden = [...dishes].filter(([key]) => key in DISH_CATEGORY_OVERRIDES);
  const other = byCategory.get('Other') ?? [];

  const lines = [
    '# Dish categories for your order data (private, not committed)',
    '',
    'Generated by `npm run dish:categories`. Rules and overrides: shared/src/lib/dish-category.ts.',
    '',
    `## Needs review: Other (${String(other.length)})`,
    '',
    ...(other.length ? other.sort().map((n) => `- ${n}`) : ['None.']),
    '',
    `## Decided by explicit overrides (${String(overridden.length)})`,
    '',
    ...overridden.map(([key, d]) => `- ${d.name} → ${String(DISH_CATEGORY_OVERRIDES[key])}`),
    '',
    '## Mapping',
    '',
    ...[...byCategory]
      .filter(([, list]) => list.length > 0)
      .flatMap(([category, list]) => [
        `### ${category} (${String(list.length)})`,
        ...list.sort().map((n) => `- ${n}`),
        '',
      ]),
  ];
  const out = join(root, 'private/dish-categories.md');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, lines.join('\n'), { mode: 0o600 });

  const used = [...byCategory].filter(([, list]) => list.length > 0);
  console.log(`Unique dishes: ${String(dishes.size)} | categories used: ${String(used.length)}`);
  console.log(
    `Categorised: ${String(dishes.size - other.length)} | Other (needs review): ${String(other.length)} | by explicit override: ${String(overridden.length)}`,
  );
  console.log(`Dishes whose original names disagree on a category: ${String(conflicts.length)}`);
  console.log('Per category: ' + used.map(([c, list]) => `${c} ${String(list.length)}`).join(', '));
  console.log('Details (private, Git-ignored): private/dish-categories.md');
}

main().catch((error: unknown) => {
  const code = error instanceof DataUnavailableError ? error.code : 'UPSTREAM_ERROR';
  console.error(`✗ ${code}: ${DATA_ERROR_MESSAGES[code]}`);
  process.exitCode = 1;
});
