/**
 * `npm run art:coverage`: which artwork files YOUR order data needs.
 *
 * The detailed report (art keys, item counts and the names of foods with no category) contains
 * personal order information, so it is written ONLY to `private/art-coverage.md` (ignored by Git)
 * on this computer. The terminal shows totals only.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  artFallbacks,
  categorize,
  foodNameKey,
  isCountedOrder,
  toDisplayName,
} from '@food-stack/shared';
import { loadEnv, sheetsConfig } from '../config/env.js';
import { createSheetsReader } from '../integrations/google-sheets/sheets-reader.js';
import { DATA_ERROR_MESSAGES, DataUnavailableError } from '../lib/data-errors.js';
import { parseSheet } from '../modules/orders/parse-sheet.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const assets = join(root, 'frontend/src/assets');
/** Plate images may be any of these formats (the same list as the frontend registry). */
const IMAGE_EXTENSIONS = ['png', 'jpg', 'jpeg', 'webp', 'avif'] as const;
const has = (folder: string, key: string): boolean =>
  (folder === 'plates' ? IMAGE_EXTENSIONS : ['png']).some((ext) =>
    existsSync(join(assets, folder, `${key}.${ext}`)),
  );
/**
 * Dish-named plate files, keyed like the frontend registry does: filename cleaned with
 * `toDisplayName`, then compared ignoring case, punctuation, "&"/"and" and word order.
 */
const dishPlateKeys = (): Set<string> =>
  new Set(
    readdirSync(join(assets, 'plates'))
      .filter((file) => new RegExp(`\\.(?:${IMAGE_EXTENSIONS.join('|')})$`, 'i').test(file))
      .map((file) => {
        const base = file.replace(/\.[^.]+$/, '');
        return foodNameKey(toDisplayName(base) || base);
      }),
  );

async function main(): Promise<void> {
  const config = sheetsConfig(loadEnv());
  if (!config) {
    console.log(
      'Not configured: set GOOGLE_SHEET_ID and a service-account credential in backend/.env.',
    );
    process.exitCode = 1;
    return;
  }
  const { orders } = parseSheet(await createSheetsReader(config).readValues());
  const items = orders.filter(isCountedOrder).flatMap((o) => o.items);
  const byKey = new Map<string, number>();
  const unmatched = new Map<string, number>();
  for (const item of items) {
    const key = categorize(item.name);
    if (key) byKey.set(key, (byKey.get(key) ?? 0) + 1);
    else {
      const name = toDisplayName(item.name) || item.name;
      unmatched.set(name, (unmatched.get(name) ?? 0) + 1);
    }
  }

  const rows = [...byKey].sort((a, b) => b[1] - a[1]);
  const plateKeys = dishPlateKeys();
  // One entry per dish as the app sees it (names differing only in case or word order are one dish).
  const dishes = [
    ...new Map(
      items.map((item) => {
        const dish = toDisplayName(item.name) || item.name;
        return [foodNameKey(dish), dish] as const;
      }),
    ).values(),
  ];
  const withoutOwnImage = dishes.filter((dish) => !plateKeys.has(foodNameKey(dish))).sort();
  const lines = [
    '# Art coverage for your order data (private, not committed)',
    '',
    'Generated by `npm run art:coverage`. Plate images go in `frontend/src/assets/plates/`, named',
    'after the dish (or an art key); PNG, JPEG, WebP or AVIF. Pile items go in',
    '`frontend/src/assets/pile/<key>.png` (single item, 512×512).',
    'See docs/design/ART-BRIEF.md for the style rules.',
    '',
    `## Dishes without their own plate image (${String(withoutOwnImage.length)} of ${String(dishes.length)})`,
    '',
    'Owner-chosen aliases in the frontend registry (PLATE_ALIASES) may still give some of these an image.',
    '',
    ...withoutOwnImage.map((dish) => `- ${dish}`),
    '',
    '## Art keys (category-level fallbacks)',
    '',
    '| Art key | Items | Plate file | Pile file | Fallback chain |',
    '| --- | ---: | --- | --- | --- |',
    ...rows.map(
      ([key, n]) =>
        `| \`${key}\` | ${String(n)} | ${has('plates', key) ? '✓ present' : '**needed**'} | ${has('pile', key) ? '✓ present' : 'needed'} | ${artFallbacks(key as never).join(' → ')} |`,
    ),
    '',
    `## Foods with no art category (${String(unmatched.size)})`,
    '',
    'These show a neutral empty plate. Tell Claude which picture each should use (a new key may be needed).',
    '',
    ...[...unmatched].sort((a, b) => b[1] - a[1]).map(([name, n]) => `- ${name} (×${String(n)})`),
    '',
  ];
  const out = join(root, 'private/art-coverage.md');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, lines.join('\n'), { mode: 0o600 });

  const missingPlates = rows.filter(([key]) => !has('plates', key)).length;
  console.log(
    `Items: ${String(items.length)} | with an art key: ${String(items.length - [...unmatched.values()].reduce((a, b) => a + b, 0))}`,
  );
  console.log(
    `Distinct art keys in your data: ${String(rows.length)} | plate images still needed: ${String(missingPlates)}`,
  );
  console.log(`Distinct foods without an art key: ${String(unmatched.size)}`);
  console.log(
    `Dishes with their own plate image: ${String(dishes.length - withoutOwnImage.length)} of ${String(dishes.length)} (before aliases)`,
  );
  console.log('Details (private, Git-ignored): private/art-coverage.md');
}

main().catch((error: unknown) => {
  const code = error instanceof DataUnavailableError ? error.code : 'UPSTREAM_ERROR';
  console.error(`✗ ${code}: ${DATA_ERROR_MESSAGES[code]}`);
  process.exitCode = 1;
});
